function recipe(
  id,
  title,
  titleEn,
  cuisine,
  category,
  time,
  ingredients,
  ingredientsEn,
  steps,
  stepsEn,
  note,
  noteEn,
  options = {},
) {
  catalogTranslations[title] = titleEn;
  ingredients.forEach((s, i) => {
    catalogTranslations[s] = ingredientsEn[i];
    const name = s.split(/\s|\d/)[0],
      en = ingredientsEn[i].replace(/\s+[\d(].*$/, "");
    if (!catalogTranslations[name]) catalogTranslations[name] = en;
  });
  steps.forEach((s, i) => (catalogTranslations[s] = stepsEn[i]));
  catalogTranslations[note] = noteEn;
  recipeCatalog.push({
    id,
    title,
    cuisine,
    category,
    time,
    ingredients,
    steps,
    note,
    ...options,
  });
}
